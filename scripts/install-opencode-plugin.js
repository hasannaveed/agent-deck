#!/usr/bin/env node

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "integrations", "opencode", "switchboard.js");
const CONTROL = path.join(ROOT, "src", "bin", "switchboardctl.js");
const GENERATED_MARKER = "// Generated by the Agent Switchboard OpenCode installer.";
const TEMPLATE_COMMAND = 'const bridgeCommand = "switchboardctl";';
const TEMPLATE_ARGUMENTS = 'const bridgeArguments = ["emit", "--harness", "opencode", "--stream"];';

function targetPath(env = process.env) {
  const configHome = env.XDG_CONFIG_HOME
    ? path.resolve(env.XDG_CONFIG_HOME)
    : path.join(homedir(), ".config");
  return path.join(configHome, "opencode", "plugins", "switchboard.js");
}

function installedSource() {
  const template = readFileSync(SOURCE, "utf8");
  if (!template.includes(TEMPLATE_COMMAND) || !template.includes(TEMPLATE_ARGUMENTS)) {
    throw new Error("The OpenCode integration template no longer contains its installer markers.");
  }
  return `${GENERATED_MARKER}\n${template
    .replace(TEMPLATE_COMMAND, `const bridgeCommand = ${JSON.stringify(process.execPath)};`)
    .replace(
      TEMPLATE_ARGUMENTS,
      `const bridgeArguments = [${JSON.stringify(CONTROL)}, "emit", "--harness", "opencode", "--stream"];`,
    )}`;
}

function install() {
  const target = targetPath();
  const content = installedSource();
  const force = process.argv.slice(2).includes("--force");

  if (existsSync(target)) {
    const metadata = lstatSync(target);
    if (metadata.isSymbolicLink() || !metadata.isFile()) {
      throw new Error(`${target} is not a regular Agent Switchboard file; it was left unchanged.`);
    }
    const current = readFileSync(target, "utf8");
    if (current === content) {
      process.stdout.write(`OpenCode integration is already installed at ${target}.\n`);
      return;
    }
    if (
      !force &&
      !current.includes(GENERATED_MARKER) &&
      !current.includes("Agent Switchboard OpenCode integration")
    ) {
      throw new Error(
        `${target} already exists and was not created by Agent Switchboard. Re-run with --force only if you intend to replace it.`,
      );
    }
  }

  mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  const temporary = path.join(path.dirname(target), `.switchboard.js.${process.pid}.tmp`);
  try {
    writeFileSync(temporary, content, { encoding: "utf8", mode: 0o600, flag: "wx" });
    renameSync(temporary, target);
  } finally {
    if (existsSync(temporary)) unlinkSync(temporary);
  }

  process.stdout.write(`Installed the OpenCode integration at ${target}.\n`);
  process.stdout.write("Restart any already-running OpenCode sessions once so they load the plugin.\n");
}

install();
